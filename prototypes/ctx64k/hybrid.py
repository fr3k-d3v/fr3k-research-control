"""Hybrid retrieval combining scoped lexical matches with supplied embeddings.

Embeddings are caller-generated by an approved model and must have equal
dimensions. This module does not fetch untrusted models or send private text.
"""
from dataclasses import dataclass
from math import sqrt, isfinite
from retrieval import Passage, terms, Hit

def cosine(a: tuple[float, ...], b: tuple[float, ...]) -> float:
    if not a or len(a) != len(b) or not all(isfinite(v) for v in a+b):
        raise ValueError("invalid embedding")
    denom = sqrt(sum(v*v for v in a))*sqrt(sum(v*v for v in b))
    return sum(x*y for x,y in zip(a,b))/denom if denom else 0.0

def hybrid(query: str, passages: tuple[Passage, ...], *,
           allowed_scopes: frozenset[str], query_vector: tuple[float, ...],
           passage_vectors: dict[str, tuple[float, ...]],
           limit: int = 5, max_chars: int = 2000) -> tuple[Hit, ...]:
    if limit < 0 or max_chars < 0:
        raise ValueError("invalid limits")
    q = terms(query)
    if not q:
        return ()
    seen = set()
    ranked = []
    for idx,p in enumerate(passages):
        if p.id in seen:
            raise ValueError("duplicate passage id")
        seen.add(p.id)
        if p.scope not in allowed_scopes:
            continue
        vector = passage_vectors.get(p.id)
        similarity = cosine(query_vector, vector) if vector is not None else 0.0
        lexical = len(q & terms(p.text))/max(1,len(q))
        score = 0.6*max(0.0,similarity)+0.4*lexical
        if score > 0:
            ranked.append((score,idx,p))
    ranked.sort(key=lambda x:(-x[0],x[1]))
    return tuple(Hit(p.id,p.source_ref,round(score*100000),p.text[:max_chars])
                 for score,_,p in ranked[:limit])
